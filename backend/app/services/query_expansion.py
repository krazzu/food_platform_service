def expand(query: str) -> str:
    """
    Expand query with domain synonyms for better vector search recall.
    'рыба' → 'рыба морепродукты лосось треска минтай ...'
    """
    lower = query.lower()
    extra: list[str] = []
    seen: set[str] = set(lower.split())

    for keyword, synonyms in SYNONYMS.items():
        if keyword in lower:
            for s in synonyms:
                if s not in seen and s not in lower:
                    extra.append(s)
                    seen.add(s)

    return f"{query} {' '.join(extra)}" if extra else query
